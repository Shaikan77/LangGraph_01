# ============================================================
# 콘솔에서 사용자의 질문을 반복해서 입력받고,
# RAG 시스템에 질문을 전달한 뒤 답변과 출처를 출력합니다.
# q, exit, quit, 종료를 입력하면 프로그램을 종료합니다.
# ============================================================
import warnings

from rag import ask

# 불필요한 경고 메시지를 화면에 표시하지 않습니다.
warnings.filterwarnings("ignore")

# ============================================================
# 프로그램 시작 시 보여줄 안내 문구입니다.
# ============================================================

BANNER = (
    "╔══════════════════════════════════════════╗\n"
    "║  전자정부지원사업 프로젝트관리 도우미    ║\n"
    "║        문서 기반 질의응답 시스템         ║\n"
    "║   종료하려면 'q' 또는 'exit' 입력        ║\n"
    "╚══════════════════════════════════════════╝"
)

# ============================================================
# 사용자에게 질문을 입력받고 답변을 출력합니다.
# ============================================================

def main():
    # 프로그램 시작 안내문을 출력합니다.
    print(BANNER)

    # 사용자가 종료할 때까지 계속 질문을 받습니다.
    while True:

        # ----------------------------------------------------
        # 질문 입력
        # ----------------------------------------------------
        try:
            question = input("\n질문 > ").strip()

        # Ctrl+C 또는 Ctrl+Z 등이 입력되면 종료합니다.
        except (KeyboardInterrupt, EOFError):
            print("\n종료합니다.")
            break

        # ----------------------------------------------------
        # 종료 명령 확인
        # ----------------------------------------------------

        # 종료 명령이면 반복문을 끝냅니다.
        if question.lower() in ("q", "exit", "quit", "종료"):
            print("종료합니다.")
            break


        # ----------------------------------------------------
        # 빈 질문 확인
        # ----------------------------------------------------

        # 아무것도 입력하지 않았다면 다시 질문을 받습니다.
        if not question:
            continue


        # ----------------------------------------------------
        # RAG 시스템에 질문 전달
        # ----------------------------------------------------
        result = ask(question)

        # ----------------------------------------------------
        # 답변 출력
        # ----------------------------------------------------
        print("\n" + "─" * 50)
        print(result["answer"])

        # ----------------------------------------------------
        # 참고 자료 출력
        # ----------------------------------------------------
        sources = result["sources"]

        # 검색된 출처가 있다면 출력합니다.
        if sources:
            print("\n참고 자료")

            # 이미 출력한 출처를 저장합니다.
            seen = set()

            # 출처를 하나씩 확인합니다.
            for source in sources:

                filename = source["file"]
                page = source["page"]

                # 파일명과 페이지 번호를 하나의 값으로 묶습니다.
                key = (filename, page)

                # 아직 출력하지 않은 출처만 출력합니다.
                if key not in seen:
                    seen.add(key)

                    print(f"   ·출처 {filename} / {page}페이지")

        # ----------------------------------------------------
        # 인용 여부 확인
        # ----------------------------------------------------

        # 답변에 올바른 인용 표시가 없으면 경고합니다.
        if result.get("cited") is False:
            print("\n⚠ 인용 표시가 확인되지 않았습니다.")

        # 한 번의 질문 처리가 끝났음을 표시합니다.
        print("─" * 50)

# ============================================================
# 이 파일을 직접 실행했을 때만 main()을 실행합니다.
# ============================================================
if __name__ == "__main__":
    main()